"""HDG discretization of the limit problem on the hypergraph of three plates (2D surfaces in 3D).

The plates E_i = {theta(s) + r e_i : 0 < s, r < 1}, theta(s) = (0, 0, s - 1/2), with
e_1 = (1, 0, 0), e_2 = (-1, 0, 0), e_3 = (0, 1, 0) meet along N = theta((0, 1)). Every plate is one
hyperedge of the initial hypergraph, whose first spanning vector is e_i and whose second spanning
vector is the direction of N. Hence, the junction is face 0 of all three hyperedges, and all three
parametrize it in the same direction. Refinement level n splits every plate into n x n squares.
"""

import math
import os

import numpy as np

import common
import limit


def write_domain(filename, d=limit.D, mu=limit.MU):
  directions = np.array([[1., 0., 0.], [-1., 0., 0.], [0., 1., 0.]])
  bottom, top = np.array([0., 0., -0.5]), np.array([0., 0., 0.5])
  points = [bottom, top]
  for direction in directions:
    points += [bottom + direction, top + direction]
  edges = []
  for i in range(3):
    edges.append({
      "points": [0, 2 + 2 * i, 1, 3 + 2 * i],
      "nodes": [0, 1 + 3 * i, 2 + 3 * i, 3 + 3 * i],
      # junction (with mass), clamped end r = 1, natural edges s = 0 and s = 1
      "types": [common.MASS, common.DIRICHLET, common.NATURAL, common.NATURAL],
      # (d, kappa, rho, c, mu): every plate contributes a third of the junction's mass density
      "props": [d[i], 1., 1., 0., mu / 3.],
    })
  common.write_geo(filename, 3, np.array(points), edges,
                   comment="Three unit-square plates meeting along a straight junction.\n"
                           "Generated by reproducibles_python/thin_plate_eigenvalues/plates.py.")


def plate_coordinates(points):
  """Plate index (0, 1, 2), s, and r of points in the interior of the plates."""
  x, y, z = points[:, 0], points[:, 1], points[:, 2]
  plate = np.where(y > 1e-12, 2, np.where(x > 0., 0, 1))
  r = np.where(plate == 2, y, np.abs(x))
  return plate, z + 0.5, r


class PlateEvaluation:
  """Quadrature on the plates and on the junction for one refinement level."""

  def __init__(self, hdg, n_quad):
    self.abscissas, weights_1d = common.gauss(n_quad)
    self.n_quad = n_quad
    # bulk: n_hyEdges x n_quad^2 points, weights d * rho * area * w_a * w_b
    points = hdg.bulk_points(list(self.abscissas)).reshape(-1, 3)
    self.plate, self.s, self.r = plate_coordinates(points)
    coeffs = hdg.coefficients().reshape(-1, 5)
    weights_2d = np.outer(weights_1d, weights_1d).T.ravel()  # first abscissa runs fastest
    self.bulk_weights = (coeffs[:, 0] * coeffs[:, 2] * hdg.hyEdge_measures())[:, None] \
      * weights_2d[None, :]
    self.bulk_weights = self.bulk_weights.ravel()
    # junction: faces of mass type, every hypernode once
    types = hdg.face_node_types()
    nodes = hdg.face_node_indices()
    first = {}
    for index in np.flatnonzero(types == common.MASS):
      first.setdefault(nodes[index], index)
    self.faces = np.array(sorted(first.values()), dtype=np.int64)
    face_points = hdg.face_points(list(self.abscissas)).reshape(-1, n_quad, 3)[self.faces]
    self.face_s = face_points[:, :, 2].ravel() + 0.5
    measures = hdg.face_measures()[self.faces]
    self.face_weights = (limit.MU * measures[:, None] * weights_1d[None, :]).ravel()
    self.hdg = hdg

  def inner_with_modes(self, vectors, modes):
    """Matrix <j_h w_a, u_b>_{H_0} for discrete eigenvectors w_a and limit eigenfunctions u_b."""
    result = np.zeros((vectors.shape[1], len(modes)))
    for a in range(vectors.shape[1]):
      x = list(vectors[:, a])
      bulk = self.hdg.bulk_values(x, list(self.abscissas))
      face = self.hdg.face_values(x, list(self.abscissas)).reshape(-1, self.n_quad)[self.faces]
      face = face.ravel()
      for b, mode in enumerate(modes):
        exact = np.choose(self.plate, [mode(i, self.s, self.r) for i in range(3)])
        result[a, b] = np.dot(self.bulk_weights, bulk * exact) + \
          np.dot(self.face_weights, face * mode.junction_value * mode.axial(self.face_s))
    return result


def run(degree, level, n_eigs=6, domain=None, tau=1.):
  """Eigenvalues and eigenvectors of the HDG method with n = level squares per plate side."""
  domain = domain or os.path.join(common.OUTPUT, "plates.geo")
  if not os.path.isfile(domain):
    os.makedirs(os.path.dirname(domain), exist_ok=True)
    write_domain(domain)
  hdg = common.problem_class(degree, 3)(domain, tau)
  hdg.set_refinement(level)
  disc = common.Discretization(hdg)
  values, vectors = disc.eigenpairs(n_eigs)
  return hdg, disc, values, vectors


def errors(hdg, disc, values, vectors, degree):
  """Eigenvalue errors and eigenspace gaps of the clusters of limit.clusters()."""
  evaluation = PlateEvaluation(hdg, degree + 6)
  result = {}
  for name, cluster in limit.clusters().items():
    modes = cluster["modes"]
    indices = list(range(cluster["first_index"], cluster["first_index"] + len(modes)))
    exact = limit.eigenvalue(cluster)
    w = vectors[:, indices]
    cross = evaluation.inner_with_modes(w, modes)
    gram_h = w.T @ (disc.mass_full @ w)
    result[name] = {
      "eigenvalues": [float(values[i]) for i in indices],
      "eigenvalue_error": float(max(abs(values[i] - exact) for i in indices)),
      "gap": common.gap(gram_h, limit.gram(modes), cross),
    }
  return result


if __name__ == "__main__":
  import sys
  degree = int(sys.argv[1]) if len(sys.argv) > 1 else 1
  for level in [2, 4, 8, 16]:
    hdg, disc, values, vectors = run(degree, level)
    res = errors(hdg, disc, values, vectors, degree)
    print(level, disc.n_unknowns(), values, {k: (v["eigenvalue_error"], v["gap"]) for k, v in
                                             res.items()})
