#!/usr/bin/env python3
"""Read per-cell, per-step energies from a wave.vtkhdf and plot totals over time.

Components in CellData/energies are laid out (block of size space_dim each):
  0: ½ ∫ n²/Cn        (axial strain)
  1: ½ ∫ m²/Cm        (bending strain)
  2: ½ ∫ v²/Cu        (translational kinetic)
  3: ½ ∫ s²/Cr        (rotational kinetic)
  4: ½ τ Σ_bdr ∫ (u-λu)²   (hybrid translational)
  5: ½ τ Σ_bdr ∫ (r-λr)²   (hybrid rotational)

Within each block the d-th entry is the contribution from edge-local direction d.
We sum over directions to get 6 physical energies, and over cells to get a total per step.
"""

import argparse
import sys
from pathlib import Path

import h5py
import matplotlib.pyplot as plt
import numpy as np


GROUP_LABELS = [
    r"$\frac{1}{2}\int n^2/C_n$  axial strain",
    r"$\frac{1}{2}\int m^2/C_m$  bending strain",
    r"$\frac{1}{2}\int v^2/C_u$  trans. kinetic",
    r"$\frac{1}{2}\int s^2/C_r$  rot. kinetic",
    r"$\frac{1}{2}\tau\,\sum\!\int(u-\lambda_u)^2$  hybrid trans.",
    r"$\frac{1}{2}\tau\,\sum\!\int(r-\lambda_r)^2$  hybrid rot.",
]


def read_energies(path):
    with h5py.File(path, "r") as f:
        E = f["/VTKHDF/CellData/energies"][...]              # (n_steps*n_cells, n_comps)
        t = f["/VTKHDF/Steps/Values"][...]                   # (n_steps,)
        off = f["/VTKHDF/Steps/CellDataOffsets/energies"][...]  # (n_steps,) row offsets
    # files written before the timowave energy() guard carry NaN kinetic entries on
    # massless welds (0/0); physically their energy is zero
    n_bad = np.isnan(E).sum() + np.isinf(E).sum()
    if n_bad:
        print(f"note: {n_bad} NaN/Inf energy entries (massless welds) treated as 0")
        E = np.nan_to_num(E, nan=0.0, posinf=0.0, neginf=0.0)
    n_steps = t.shape[0]
    n_comps = E.shape[1]
    assert n_comps % 6 == 0, f"expected n_comps divisible by 6, got {n_comps}"
    space_dim = n_comps // 6

    # rows for step s: [off[s], off[s+1]); last step runs to end
    bounds = np.append(off, E.shape[0])
    per_step = np.zeros((n_steps, n_comps), dtype=E.dtype)
    for s in range(n_steps):
        per_step[s] = E[bounds[s]:bounds[s+1]].sum(axis=0)

    # collapse the d-axis: (n_steps, 6, space_dim) -> (n_steps, 6)
    grouped = per_step.reshape(n_steps, 6, space_dim).sum(axis=2)
    return t, grouped, per_step, space_dim


def read_energies_csv(path):
    """Reduced per-step sidecar written by --save; returns (t, grouped) only."""
    d = np.genfromtxt(path, delimiter=",", names=True)
    cols = ["axial_strain", "bending_strain", "trans_kinetic", "rot_kinetic",
            "hybrid_trans", "hybrid_rot"]
    grouped = np.column_stack([np.atleast_1d(d[c]) for c in cols])
    return np.atleast_1d(d["t"]), grouped


def write_tikz(prefix, t, grouped, log=False, percent=False):
    """PREFIX.csv + self-contained PREFIX.tex with the four collapsed lines:
    strain (axial+bending), kinetic (trans+rot), hybrid (HDG stab.), total.
    With percent=True the csv still holds the raw values (whose unit is the
    code's internal one, e.g. lengths in um) and the plot rescales them to
    percentages of the maximum total energy."""
    prefix = Path(prefix)
    if str(prefix.parent) not in (".", ""):
        prefix.parent.mkdir(parents=True, exist_ok=True)
    tex_path = Path(str(prefix) + ".tex")
    csv_path = Path(str(prefix) + ".csv")

    strain = grouped[:, 0] + grouped[:, 1]
    kinetic = grouped[:, 2] + grouped[:, 3]
    hybrid = grouped[:, 4] + grouped[:, 5]
    total = grouped.sum(axis=1)
    np.savetxt(csv_path, np.column_stack([t, strain, kinetic, hybrid, total]),
               delimiter=",", comments="", header="t,strain,kinetic,hybrid,total")

    # single-word legend entries + footnotesize: at paper axis widths (~5cm)
    # four "... energy" rows cover half the plot
    series = [("strain", "strain"), ("kinetic", "kinetic"), ("hybrid", "hybrid")]
    L = [
        "% generated by experiments/energy.py --tikz",
        f"% standalone: latexmk -pdf {tex_path.name} (keep {csv_path.name} next to it)",
        "% manuscript: \\usepackage{standalone} \\usepackage{pgfplots} \\pgfplotsset{compat=newest},",
        "%   then \\input this file -- the preamble below is skipped, fonts come from the manuscript.",
        "%   \\renewcommand{\\figurewidth}{...} (default \\linewidth) and \\plotdatadir (default empty,",
        "%   set with trailing /) before \\input as needed.",
        "%   add \\usetikzlibrary{external} \\tikzexternalize to cache figures across manuscript compiles.",
    ]
    if percent:
        L.append(f"% energies are shown as percentages of the maximum total energy"
                 f" Emax = {total.max():.10g},")
        L.append(f"% attained at t = {t[total.argmax()]:.6g}; the csv holds the raw values.")
    L += [
        "\\documentclass{standalone}",
        "\\usepackage{amsmath}",
        "\\usepackage{pgfplots}",
        "\\pgfplotsset{compat=newest}",
        "\\begin{document}",
        "\\providecommand{\\figurewidth}{\\linewidth}",
        "\\providecommand{\\plotdatadir}{}",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  width=\\figurewidth,",
        "  xlabel={$t$ [s]},",
        "  ylabel={energy [\\%]}," if percent else "  ylabel={energy},",
    ]
    if log:
        L.append("  ymode=log,")
    L.extend([
        # south east + 2 columns: the box stays low, only the ~0 hybrid line
        # runs behind it, even at paper axis widths
        "  legend pos=south east,",
        "  legend columns=2,",
        "  legend style={legend cell align=left, font=\\footnotesize},",
        "]",
    ])
    def yspec(col):
        return (f"y expr=100*\\thisrow{{{col}}}/{total.max():.10g}" if percent
                else f"y={col}")
    for col, label in series:
        L.append(f"\\addplot+[mark=none, thick] table[x=t, {yspec(col)}, col sep=comma] "
                 f"{{\\plotdatadir {csv_path.name}}};")
        L.append(f"\\addlegendentry{{{label}}}")
    L.append(f"\\addplot[black, thick] table[x=t, {yspec('total')}, col sep=comma] "
             f"{{\\plotdatadir {csv_path.name}}};")
    L.append("\\addlegendentry{total}")
    L.extend(["\\end{axis}", "\\end{tikzpicture}", "\\end{document}"])

    tex_path.write_text("\n".join(L) + "\n")
    print(f"wrote {tex_path} + {csv_path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("file", nargs="?", default="output/energy/wave.vtkhdf",
                    help="path to wave.vtkhdf, or a reduced -energy.csv sidecar")
    ap.add_argument("-o", "--save", help="save plot to this path instead of showing")
    ap.add_argument("--log", action="store_true", help="log scale on y")
    ap.add_argument("--percent", action="store_true",
                    help="--tikz: plot energies as percentages of the maximum "
                         "total energy (the csv keeps the raw values)")
    ap.add_argument("--all", action="store_true",
                    help="plot all 6*space_dim raw components instead of grouped")
    ap.add_argument("--tikz", metavar="PREFIX",
                    help="write PREFIX.csv + standalone PREFIX.tex with the four "
                         "collapsed lines (strain, kinetic, hybrid, total) and exit "
                         "unless --save is also given")
    args = ap.parse_args()

    if args.file.endswith(".csv"):
        if args.all:
            sys.exit("--all needs the wave.vtkhdf (the csv sidecar is already grouped)")
        t, grouped = read_energies_csv(args.file)
        raw, space_dim = None, None
    else:
        t, grouped, raw, space_dim = read_energies(args.file)

    if args.tikz:
        write_tikz(args.tikz, t, grouped, log=args.log, percent=args.percent)
        if not args.save:
            return
    total = grouped.sum(axis=1)

    physical = grouped[:, :4].sum(axis=1)  # n, m strain + v, s kinetic
    hybrid   = grouped[:, 4:].sum(axis=1)  # u, r hybrid penalty (HDG stabilization)

    fig, ax = plt.subplots(figsize=(8, 5))
    if args.all:
        for c in range(raw.shape[1]):
            g, d = divmod(c, space_dim)
            ax.plot(t, raw[:, c], label=f"{GROUP_LABELS[g].split('  ')[1]} (d={d})",
                    linewidth=1)
    else:
        for c in range(grouped.shape[1]):
            ax.plot(t, grouped[:, c], label=GROUP_LABELS[c], linewidth=1)
    ax.plot(t, physical, label="physical (n+m+v+s)", color="tab:green", linewidth=2, linestyle="--")
    ax.plot(t, hybrid,   label="hybrid (u+r, HDG stab.)", color="tab:red", linewidth=2, linestyle="--")
    ax.plot(t, total, label="total", color="k", linewidth=2)

    ax.set_xlabel("time")
    ax.set_ylabel("energy")
    if args.log:
        ax.set_yscale("log")
    ax.legend(loc="best", fontsize=8)
    ax.grid(True, alpha=0.3)
    fig.tight_layout()

    if args.save:
        Path(args.save).parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(args.save, bbox_inches="tight", pad_inches=0.05)
        # pgfplots-ready sidecar with the reduced data (tikz versions read this csv)
        base = args.save.rsplit(".", 1)[0]
        cols = np.column_stack([t, grouped, physical, hybrid, total])
        np.savetxt(base + ".csv", cols, delimiter=",", comments="",
                   header="t,axial_strain,bending_strain,trans_kinetic,rot_kinetic,"
                          "hybrid_trans,hybrid_rot,physical,hybrid,total")
        print(f"wrote {base}.csv")
        print(f"wrote {args.save}", file=sys.stderr)
    else:
        plt.show()


if __name__ == "__main__":
    main()
